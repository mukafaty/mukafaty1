/** بحث مرن باسم المدينة يتجاهل الهمزات والتاء المربوطة و«ال». */
export function normalizeArabic(value: string): string {
  return value
    .trim()
    .replace(/[\u064B-\u0652]/g, "")
    .replace(/[أإآ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/\s+/g, " ");
}

export function searchCities(query: string): string[] {
  const q = normalizeArabic(query);
  if (!q) return [...SAUDI_CITIES];
  return SAUDI_CITIES.filter((c) => normalizeArabic(c).includes(q));
}
